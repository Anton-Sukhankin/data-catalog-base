import { expect, test } from '@playwright/test';

test('cards match the reference within domain groups and preserve their chosen identity', async ({ page }) => {
  await page.setViewportSize({ width: 1440, height: 900 });
  const errors: string[] = [];
  page.on('pageerror', (error) => errors.push(error.message));
  page.on('console', (message) => { if (message.type() === 'error' || message.type() === 'warning') errors.push(message.text()); });
  await page.goto('/preview/navigation?paginationDemo=0');
  await page.getByRole('button', { name: 'Карточный вид', exact: true }).click();
  const reports = page.getByRole('navigation', { name: 'Разделы каталога' }).getByRole('button', { name: 'Отчёты', exact: true });
  const home = page.getByRole('navigation', { name: 'Разделы каталога' }).getByRole('button', { name: 'Главная', exact: true });
  const backToCards = page.getByRole('navigation', { name: 'Хлебные крошки', exact: true }).getByRole('button', { name: 'Отчёты', exact: true });
  const surface = page.getByRole('region', { name: 'Примеры карточек отчётов' });
  const verified = page.locator('[data-card-report-id="demo-report-summary"]');
  const unverified = page.locator('[data-card-report-id="demo-report-occupancy"]');
  await expect(verified).toBeVisible();
  await expect(unverified).toBeVisible();
  expect((await verified.boundingBox())?.width).toBe(544);
  expect((await verified.boundingBox())?.height).toBe(98);
  await expect(surface.locator('[data-card-report-id]')).toHaveCount(10);
  await expect(surface.getByRole('region')).toHaveCount(6);
  await expect(surface).toHaveCSS('background-color', 'rgb(243, 244, 249)');
  expect((await surface.boundingBox())?.width).toBe(1128);
  const hospitality = surface.getByRole('region', { name: 'Домен «Гостеприимство»' });
  await expect(hospitality.locator('[data-card-report-id]')).toHaveCount(5);
  await expect(hospitality.getByLabel('5 позиций')).toBeVisible();
  const verifiedLabel = verified.getByText('Проверено:', { exact: true });
  await expect(verifiedLabel).toBeVisible();
  await expect(verified.getByText('Проверено', { exact: true })).toHaveCount(0);
  await expect(unverified.getByText('Не проверено', { exact: true })).toBeVisible();
  await expect(unverified.getByText('Губина Екатерина Игоревна')).toHaveCount(0);
  const reviewer = verified.getByText('Губина Екатерина Игоревна', { exact: true });
  await expect(reviewer).toHaveCSS('font-size', '12px');
  await expect(reviewer).toHaveCSS('color', await verifiedLabel.evaluate(label => getComputedStyle(label).color));
  const badge = verified.locator('img[src$="verified-badge.svg"]');
  const documentGlyph = verified.locator('img[src$="report-document.svg"]');
  expect((await badge.boundingBox())!.y).toBeLessThan((await documentGlyph.boundingBox())!.y);
  const description = verified.locator('[data-card-description]');
  expect((await description.boundingBox())!.y).toBeGreaterThan((await verified.getByText('Сводный отчёт Гостеприимства', { exact: true }).boundingBox())!.y);
  await expect(description).not.toContainText('Гостеприимство');
  const iconBox = await documentGlyph.locator('..').boundingBox();
  const textBox = await description.locator('..').boundingBox();
  expect(textBox!.x).toBeGreaterThan(iconBox!.x + iconBox!.width);
  expect(Math.abs((textBox!.y + textBox!.height / 2) - (iconBox!.y + iconBox!.height / 2))).toBeLessThan(1);
  await expect(verified.getByText('Сводный отчёт Гостеприимства', { exact: true })).toHaveCSS('text-overflow', 'ellipsis');
  const mainTitle = verified.locator('[data-card-title]');
  await expect(mainTitle).not.toHaveAttribute('data-overflow-clipped');
  await page.setViewportSize({ width: 1024, height: 900 });
  await expect(mainTitle).toHaveAttribute('data-overflow-clipped', 'true');
  expect(await mainTitle.evaluate(node => node.scrollWidth > node.clientWidth)).toBe(true);
  await mainTitle.hover();
  await expect(page.getByRole('tooltip')).toHaveText('Сводный отчёт Гостеприимства');
  await page.setViewportSize({ width: 1440, height: 900 });
  await expect(mainTitle).not.toHaveAttribute('data-overflow-clipped');
  await expect(page.getByRole('tooltip')).toHaveCount(0);
  const lastCard = surface.locator('[data-card-report-id="demo-report-finance-plan"]');
  await lastCard.scrollIntoViewIfNeeded();
  await expect(lastCard).toBeInViewport();
  await verified.scrollIntoViewIfNeeded();
  await page.evaluate(() => document.fonts.ready);
  await page.mouse.move(1200, 750);
  await page.screenshot({ path: 'verification/current/cards/context.png', fullPage: true });
  await verified.screenshot({ path: 'verification/current/cards/verified.png' });
  await unverified.screenshot({ path: 'verification/current/cards/unverified.png' });
  await verified.hover();
  await expect(verified).toHaveCSS('border-color', 'rgb(64, 143, 231)');
  await expect(mainTitle).toHaveCSS('color', 'rgb(0, 103, 220)');
  await expect(documentGlyph.locator('..')).toHaveCSS('background-color', 'rgb(231, 242, 255)');
  await expect(verified.locator('img[src$="report-document-hover.svg"]')).toHaveCSS('opacity', '1');
  expect((await verified.locator('img[src$="report-document-hover.svg"]').boundingBox())?.width).toBe(16);
  await expect(reviewer).toHaveText('Губина Екатерина Игоревна');
  await verified.screenshot({ path: 'verification/current/cards/hover.png' });
  await verified.getByRole('button', { name: 'Редактировать отчёт «Сводный отчёт Гостеприимства»' }).click();
  await expect(page.getByRole('status')).toHaveText('Редактирование отчёта «Сводный отчёт Гостеприимства» пока не реализовано.');
  await expect(page.locator('[data-report-id]')).toHaveCount(0);
  await verified.getByRole('button', { name: 'Открыть отчёт «Сводный отчёт Гостеприимства»' }).click();
  await expect(page.locator('[data-report-id]')).toHaveAttribute('data-report-id', 'demo-report-summary');
  await backToCards.click();
  await unverified.getByRole('button', { name: 'Открыть отчёт «Динамика заселения»' }).click();
  await expect(page.locator('[data-report-id]')).toHaveAttribute('data-report-id', 'demo-report-occupancy');
  await expect(page.getByRole('heading', { name: 'Динамика заселения', exact: true })).toBeVisible();
  await expect(page.locator('dl')).toContainText('Пульс BI · демо');
  await expect(page.locator('dl')).toContainText('Домиленд');
  await backToCards.click();
  await page.setViewportSize({ width: 1920, height: 1080 });
  expect((await verified.boundingBox())?.width).toBe(520);
  await page.screenshot({ path: 'verification/current/cards/context-wide.png', fullPage: true });
  await page.setViewportSize({ width: 1440, height: 900 });
  await reports.click();
  await expect(page.getByRole('region', { name: 'Таблица отчётов', exact: true })).toBeVisible();
  await home.click();
  await page.getByRole('button', { name: 'Карточный вид', exact: true }).click();
  await expect(verified).toBeVisible();
  const search = page.getByRole('combobox', { name: 'Поиск по каталогу' });
  await search.fill('Динамика');
  await page.getByRole('button',{name:'Открыть паспорт «Динамика заселения»',exact:true}).click();
  await expect(page.locator('[data-report-id]')).toHaveAttribute('data-report-id', 'demo-report-occupancy');
  expect(errors).toEqual([]);
});
