import { expect, test } from '@playwright/test';

test('general panel applies one atomic draft, cancels all close paths, and synchronizes with column filters', async ({ page }) => {
  await page.setViewportSize({ width: 1440, height: 900 });
  const errors: string[] = [];
  page.on('pageerror', error => errors.push(error.message));
  page.on('console', message => { if (['warning', 'error'].includes(message.type())) errors.push(message.text()); });
  await page.goto('/preview/navigation?tableCase=legacy-two-pages');
  await page.getByRole('navigation', { name: 'Разделы каталога' }).getByRole('button', { name: 'Отчёты', exact: true }).click();
  const table = page.getByRole('region', { name: 'Таблица отчётов', exact: true });
  const rows = page.locator('[data-table-report-id]');
  const open = page.getByRole('button', { name: 'Открыть фильтры отчётов', exact: true });
  const panel = page.getByRole('dialog', { name: 'Фильтры отчётов', exact: true });
  const popup = page.locator('[data-panel-value-list]');
  const field = (name: string) => panel.locator(`[data-panel-field="${name}"]`);
  const apply = () => panel.getByRole('button', { name: 'Применить', exact: true }).click();
  await open.click();
  expect(await panel.boundingBox()).toEqual({ x: 936, y: 24, width: 480, height: 852 });
  expect(await panel.locator('[data-panel-field]').evaluateAll(elements => elements.map(element => element.getAttribute('data-panel-field'))))
    .toEqual(['domain', 'title', 'status', 'owner', 'masterSystem', 'platform', 'mau', 'lastViewed']);
  await expect(panel.getByRole('button', { name: 'Применить', exact: true })).toBeDisabled();
  await field('domain').click();
  expect((await popup.boundingBox())?.width).toBe(440);
  await popup.getByRole('checkbox', { name: 'Гостеприимство', exact: true }).check();
  await popup.getByRole('checkbox', { name: 'Финансы', exact: true }).check();
  await expect(panel.locator('[data-panel-count]')).toHaveText('1');
  await expect(rows).toHaveCount(8);
  await panel.getByRole('heading').click();
  await field('status').click();
  await expect(popup.getByRole('checkbox')).toHaveCount(0);
  await expect(popup.getByRole('radio', { name: 'Все', exact: true })).toBeChecked();
  await popup.getByRole('radio', { name: 'Проверено', exact: true }).check();
  await expect(panel.locator('[data-panel-count]')).toHaveText('2');
  await apply();
  await expect(panel).toHaveCount(0);
  await expect(rows).toHaveCount(4);
  await expect(table.getByRole('button', { name: 'Сбросить фильтр «Домен»' })).toBeVisible();
  await open.click();
  await expect(panel.getByRole('button', { name: 'Применить', exact: true })).toBeDisabled();
  await panel.getByRole('button', { name: 'Сбросить', exact: true }).click();
  await expect(panel).toBeVisible();
  await expect(panel.locator('[data-panel-count]')).toHaveCount(0);
  await expect(rows).toHaveCount(4);
  await expect(panel.getByRole('button', { name: 'Применить', exact: true })).toBeEnabled();
  await panel.getByRole('button', { name: 'Закрыть', exact: true }).click();
  await expect(open).toBeFocused();
  await expect(rows).toHaveCount(4);
  await open.click();
  await expect(panel.locator('[data-panel-count]')).toHaveText('2');
  await panel.getByRole('button', { name: 'Сбросить', exact: true }).click();
  await apply();
  await expect(rows).toHaveCount(8);
  await expect(page.getByRole('button', { name: /^Сбросить все фильтры:/ })).toHaveCount(0);
  for (const closeBy of ['escape', 'backdrop'] as const) {
    await open.click();
    await field('domain').click();
    await popup.getByRole('checkbox', { name: 'Гостеприимство', exact: true }).check();
    if (closeBy === 'escape') await page.keyboard.press('Escape');
    else await page.locator('[data-panel-backdrop]').click({ position: { x: 100, y: 400 } });
    await expect(panel).toHaveCount(0);
    await expect(rows).toHaveCount(8);
  }
  await open.click();
  expect((await field('mau').boundingBox())!.width).toBe(440);
  await panel.getByRole('spinbutton', { name: 'MAU: от', exact: true }).fill('91');
  await panel.getByRole('spinbutton', { name: 'MAU: до', exact: true }).fill('91');
  await apply();
  await expect(rows).toHaveCount(1);
  await expect(table.locator('[data-table-report-id="demo-report-motivation"]')).toBeVisible();
  await table.getByRole('button', { name: 'Фильтр «MAU»', exact: true }).click();
  await expect(page.getByRole('dialog', { name: 'Фильтр: MAU' }).getByRole('spinbutton', { name: 'MAU: от', exact: true })).toHaveValue('91');
  await expect(page.getByRole('dialog', { name: 'Фильтр: MAU' }).getByRole('spinbutton', { name: 'MAU: до', exact: true })).toHaveValue('91');
  await page.keyboard.press('Escape');
  await page.getByRole('button', { name: /^Сбросить все фильтры:/ }).click();
  await expect(rows).toHaveCount(8);
  await open.click();
  await page.screenshot({ path: 'verification/current/panel/catalog-default.png', fullPage: false });
  await page.keyboard.press('Escape');
  expect(errors).toEqual([]);
});
