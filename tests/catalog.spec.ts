import { expect, test } from '@playwright/test';

test('catalog switches the same real page between views, preserves conditions and returns from its selected object', async ({ page }) => {
  await page.setViewportSize({ width: 1440, height: 900 });
  const errors: string[] = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto('/preview/navigation?section=reports&tableCase=legacy-two-pages');
  const table = page.getByRole('region', { name: 'Таблица отчётов', exact: true });
  const rowIds = () => table.locator('[data-table-report-id]').evaluateAll(nodes => nodes.map(node => node.getAttribute('data-table-report-id')));
  await expect(table.locator('[data-table-report-id]')).toHaveCount(8);
  const initialIds = await rowIds();
  await page.getByRole('button', { name: 'Карточный вид', exact: true }).click();
  const cards = page.getByRole('region', { name: 'Примеры карточек отчётов' });
  await expect(cards.locator('[data-card-report-id]')).toHaveCount(initialIds.length);
  expect(await cards.locator('[data-card-report-id]').evaluateAll(nodes => nodes.map(node => node.getAttribute('data-card-report-id')))).toEqual(initialIds);
  const picker = page.getByRole('group', { name: 'Вид представления', exact: true });
  expect(await picker.boundingBox()).toEqual({x:1266,y:64,width:102,height:40});
  expect(await cards.boundingBox()).toEqual({x:312,y:136,width:1088,height:764});
  await page.screenshot({path:'verification/current/catalog/cards.png'});
  const sourceOnly = cards.locator('[data-card-report-id="demo-report-sales-plan"]');
  await sourceOnly.getByRole('button', { name: 'Открыть отчёт «План-Факт продажи»', exact: true }).click();
  await expect(page).toHaveURL(/report=demo-report-sales-plan/);
  await expect(page.locator('[data-report-id]')).toHaveAttribute('data-report-id','demo-report-sales-plan');
  await page.getByRole('navigation',{name:'Хлебные крошки',exact:true}).getByRole('button',{name:'Отчёты',exact:true}).click();
  await expect(page.getByRole('button', {name:'Карточный вид',exact:true})).toHaveAttribute('aria-pressed','true');
  await expect(cards.locator('[data-card-report-id]')).toHaveCount(8);
  await page.getByRole('navigation',{name:'Страницы отчётов'}).getByRole('button',{name:'Следующая страница'}).click();
  await expect(cards.locator('[data-card-report-id]')).toHaveAttribute('data-card-report-id','demo-report-finance-plan');
  await page.getByRole('button',{name:'Табличный вид',exact:true}).click();
  await expect(table.locator('[data-table-report-id]')).toHaveAttribute('data-table-report-id','demo-report-finance-plan');
  await page.getByRole('button',{name:'Открыть фильтры отчётов',exact:true}).click();
  const panel=page.getByRole('dialog',{name:'Фильтры',exact:true});
  await panel.locator('[data-panel-field="domain"]').click();
  await page.locator('[data-panel-value-list]').getByRole('checkbox',{name:'Гостеприимство',exact:true}).check();
  await panel.getByRole('button',{name:'Применить',exact:true}).click();
  await expect(table.locator('[data-table-report-id]')).toHaveCount(5);
  await page.getByRole('button',{name:'Карточный вид',exact:true}).click();
  await expect(cards.locator('[data-card-report-id]')).toHaveCount(5);
  await cards.locator('[data-card-report-id="demo-report-debt"]').getByRole('button',{name:'Открыть отчёт «Отчёт по дебиторской задолженности»',exact:true}).click();
  await expect(page.locator('[data-report-id]')).toHaveAttribute('data-report-id','demo-report-debt');
  await page.goBack();
  await expect(cards.locator('[data-card-report-id]')).toHaveCount(5);
  await page.goForward();
  await expect(page.locator('[data-report-id]')).toHaveAttribute('data-report-id','demo-report-debt');
  await page.reload();
  await expect(page.getByRole('heading',{name:'Отчёт по дебиторской задолженности',exact:true})).toBeVisible();
  expect(errors).toEqual([]);
});

test('browser history closes a pending filter draft without applying it to another list',async({page})=>{
  await page.goto('/preview/navigation');
  const navigation=page.getByRole('navigation',{name:'Разделы каталога'});
  await navigation.getByRole('button',{name:'Отчёты',exact:true}).click();
  await page.getByRole('button',{name:'Открыть фильтры отчётов',exact:true}).click();
  const panel=page.getByRole('dialog',{name:'Фильтры',exact:true});
  await panel.locator('[data-panel-field="domain"]').click();
  await page.locator('[data-panel-value-list]').getByRole('checkbox',{name:'Финансы',exact:true}).check();
  await page.goBack();
  await expect(panel).toHaveCount(0);
  await expect(page.locator('[data-table-report-id]')).toHaveCount(15);
  await navigation.getByRole('button',{name:'Отчёты',exact:true}).click();
  await expect(page.locator('[data-table-report-id]')).toHaveCount(15);
  await expect(page.getByRole('button',{name:/^Сбросить все фильтры:/})).toHaveCount(0);
});

test('sort directions are drafts until Apply, work on displayed values and restore the source order', async ({page}) => {
  await page.setViewportSize({width:1440,height:900});
  await page.goto('/preview/navigation?section=reports&tableCase=single-page');
  const table=page.getByRole('region',{name:'Таблица отчётов',exact:true});
  const ids=()=>table.locator('[data-table-report-id]').evaluateAll(nodes=>nodes.map(node=>node.getAttribute('data-table-report-id')));
  await expect(table.locator('[data-table-report-id]')).toHaveCount(9);
  const original=await ids();
  const open=(name:string)=>table.getByRole('button',{name:`Фильтр «${name}»`,exact:true}).click();
  const menu=page.getByRole('dialog',{name:'Фильтр: Отчёт',exact:true});
  await open('Отчёт');
  await menu.getByRole('button',{name:'А → Я',exact:true}).click();
  expect(await ids()).toEqual(original);
  await page.keyboard.press('Escape');
  expect(await ids()).toEqual(original);
  await open('Отчёт');
  await menu.getByRole('button',{name:'А → Я',exact:true}).click();
  await menu.getByRole('button',{name:'Применить',exact:true}).click();
  expect((await ids()).slice(0,5)).toEqual(['demo-report-occupancy','demo-report-motivation','demo-report-debt','demo-report-summary','demo-report-management']);
  const arrow=table.locator('[data-sort-indicator="asc"]');
  expect(await arrow.boundingBox()).toEqual({x:398,y:136,width:16,height:16});
  await expect.poll(()=>arrow.evaluate(node=>(node as HTMLImageElement).naturalWidth)).toBe(16);
  await page.screenshot({path:'verification/current/catalog/sorted-title.png'});
  await open('Отчёт');
  await expect(menu.getByRole('button',{name:'А → Я',exact:true})).toHaveAttribute('aria-pressed','true');
  await menu.getByRole('button',{name:'А → Я',exact:true}).click();
  await menu.getByRole('button',{name:'Применить',exact:true}).click();
  expect(await ids()).toEqual(original);
  await expect(table.locator('[data-sort-indicator]')).toHaveCount(0);
  await open('MAU');
  const numeric=page.getByRole('dialog',{name:'Фильтр: MAU',exact:true});
  await numeric.getByRole('button',{name:'По возрастанию',exact:true}).click();
  await numeric.getByRole('button',{name:'Применить',exact:true}).click();
  expect((await ids()).slice(0,5)).toEqual(['demo-report-management','demo-report-debt','demo-report-motivation','demo-report-occupancy','demo-report-summary']);
  await open('Отчёт');
  await menu.getByRole('button',{name:'Сбросить',exact:true}).click();
  await expect(table.getByRole('button',{name:'Сбросить сортировку «MAU»',exact:true})).toBeVisible();
  await table.getByRole('button',{name:'Сбросить сортировку «MAU»',exact:true}).press('Enter');
  expect(await ids()).toEqual(original);
  await expect(table.getByRole('button',{name:'Фильтр «MAU»',exact:true})).toBeFocused();
  await open('MAU');
  await numeric.getByRole('button',{name:'По возрастанию',exact:true}).click();
  await numeric.getByRole('button',{name:'Применить',exact:true}).click();
  await open('MAU');
  await numeric.getByRole('button',{name:'Сбросить',exact:true}).click();
  await expect(numeric).toHaveCount(0);
  expect(await ids()).toEqual(original);
});
