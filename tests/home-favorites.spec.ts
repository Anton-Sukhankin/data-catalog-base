import { expect, test } from '@playwright/test';

test('favorites preserve ten identities, canonical state, and applied conditions across card and table views', async ({ page }) => {
  await page.setViewportSize({ width: 1440, height: 900 });
  const errors: string[] = [];
  page.on('pageerror', error => errors.push(error.message));
  page.on('console', message => { if (['warning', 'error'].includes(message.type())) errors.push(message.text()); });
  await page.goto('/preview/navigation?paginationDemo=0');
  await expect(page.getByRole('button', { name: 'Табличный вид', exact: true })).toHaveAttribute('aria-pressed', 'true');
  await page.getByRole('button', { name: 'Карточный вид', exact: true }).click();
  const cards = page.getByRole('region', { name: 'Примеры карточек отчётов' });
  const table = page.getByRole('region', { name: 'Таблица отчётов', exact: true });
  const tableView = page.getByRole('button', { name: 'Табличный вид', exact: true });
  const cardView = page.getByRole('button', { name: 'Карточный вид', exact: true });
  const panel = page.getByRole('dialog', { name: 'Фильтры избранных отчётов', exact: true });
  const popup = page.locator('[data-panel-value-list]');
  const open = page.getByRole('button', { name: 'Открыть фильтры отчётов', exact: true });
  await expect(cards.locator('[data-card-report-id]')).toHaveCount(10);
  expect(await page.locator('[data-home-controls]').boundingBox()).toEqual({ x: 296, y: 104, width: 1128, height: 90 });
  expect(await cards.boundingBox()).toEqual({ x: 296, y: 210, width: 1128, height: 690 });
  const cardIds = await cards.locator('[data-card-report-id]').evaluateAll(elements => elements.map(element => element.getAttribute('data-card-report-id')));
  await page.evaluate(() => document.fonts.ready);
  await page.screenshot({ path: 'verification/current/home/cards.png', fullPage: false });
  await tableView.click();
  await expect(table.locator('[data-table-report-id]')).toHaveCount(10);
  expect(await table.locator('[data-table-report-id]').evaluateAll(elements => elements.map(element => element.getAttribute('data-table-report-id')))).toEqual(cardIds);
  expect(await table.boundingBox()).toEqual({ x: 296, y: 210, width: 1128, height: 690 });
  await expect(table.getByAltText('Проверен', { exact: true })).toHaveCount(4);
  const construction = table.locator('[data-table-report-id="demo-report-construction"]');
  await expect(construction.getByRole('cell').nth(3)).toHaveText('Строительство');
  await expect(construction.getByRole('cell').nth(1)).toContainText('—');
  await expect(construction.getByRole('cell').nth(6)).toHaveText('—');
  await expect(table.getByRole('navigation', { name: 'Страницы избранных отчётов' })).toHaveCount(0);
  await page.screenshot({ path: 'verification/current/home/table.png', fullPage: false });
  await open.click();
  expect(await panel.locator('[data-panel-field]').evaluateAll(elements => elements.map(element => element.getAttribute('data-panel-field'))))
    .toEqual(['domain', 'title', 'status', 'owner', 'masterSystem', 'platform', 'mau', 'lastViewed']);
  await panel.locator('[data-panel-field="domain"]').click();
  await expect(popup.getByRole('searchbox')).toHaveCount(0);
  await expect(popup.getByRole('checkbox', { name: 'Все домены', exact: true })).toBeChecked();
  await popup.getByRole('checkbox', { name: 'Строительство', exact: true }).check();
  await panel.getByRole('button', { name: 'Применить', exact: true }).click();
  await expect(table.locator('[data-table-report-id]')).toHaveCount(1);
  await expect(construction).toBeVisible();
  await cardView.click();
  await expect(cards.locator('[data-card-report-id]')).toHaveCount(1);
  await expect(cards.locator('[data-card-report-id="demo-report-construction"]')).toBeVisible();
  await tableView.click();
  const domainFilter = table.getByRole('button', { name: 'Фильтр «Домен»', exact: true });
  await domainFilter.click();
  const columnMenu = page.getByRole('dialog', { name: 'Фильтр: Домен' });
  const domainColumn = domainFilter.locator('xpath=ancestor::*[@role="columnheader"]');
  const anchor = (await domainColumn.boundingBox())!;
  expect((await columnMenu.boundingBox())!.y - anchor.y - anchor.height).toBe(8);
  await expect(columnMenu.getByRole('checkbox', { name: 'Строительство', exact: true })).toBeChecked();
  await columnMenu.getByRole('button', { name: 'Сбросить', exact: true }).click();
  await expect(columnMenu).toHaveCount(0);
  await expect(table.locator('[data-table-report-id]')).toHaveCount(10);
  await open.click();
  await panel.locator('[data-panel-field="status"]').click();
  await popup.getByRole('radio', { name: 'Не проверено', exact: true }).check();
  await panel.getByRole('button', { name: 'Применить', exact: true }).click();
  await expect(table.locator('[data-table-report-id]')).toHaveCount(6);
  await cardView.click();
  await expect(cards.locator('[data-card-report-id]')).toHaveCount(6);
  await expect(cards.getByText('Не проверено', { exact: true })).toHaveCount(6);
  await page.getByRole('navigation', { name: 'Разделы каталога' }).getByRole('button', { name: 'Отчёты', exact: true }).click();
  await expect(page.getByRole('region', { name: 'Таблица отчётов', exact: true }).locator('[data-table-report-id]')).toHaveCount(9);
  await page.getByRole('navigation', { name: 'Разделы каталога' }).getByRole('button', { name: 'Главная', exact: true }).click();
  await expect(table.locator('[data-table-report-id]')).toHaveCount(10);
  await expect(page.getByRole('button', { name: /^Сбросить все фильтры:/ })).toHaveCount(0);
  await cardView.click();
  await expect(cards.locator('[data-card-report-id]')).toHaveCount(10);
  await page.getByRole('tab', { name: /^Источники/ }).click();
  await expect(cards).toHaveCount(0);
  await page.getByRole('tab', { name: /^Отчёты/ }).click();
  await expect(cards.locator('[data-card-report-id]')).toHaveCount(10);
  expect(errors).toEqual([]);
});

test('favorite pages retain the same objects when the view changes and filtering returns to page one', async ({ page }) => {
  await page.setViewportSize({ width: 1440, height: 900 });
  await page.goto('/preview/navigation?favoriteCase=two-pages');
  await page.getByRole('button', { name: 'Карточный вид', exact: true }).click();
  const cards = page.getByRole('region', { name: 'Примеры карточек отчётов' });
  const pager = page.getByRole('navigation', { name: 'Страницы избранных отчётов' });
  await expect(cards.locator('[data-card-report-id]')).toHaveCount(8);
  await pager.getByRole('button', { name: 'Следующая страница' }).click();
  await expect(cards.locator('[data-card-report-id]')).toHaveCount(2);
  const secondIds = await cards.locator('[data-card-report-id]').evaluateAll(elements => elements.map(element => element.getAttribute('data-card-report-id')));
  await expect(pager).toContainText('9–10 из 10 · 8 на странице');
  await page.getByRole('button', { name: 'Табличный вид', exact: true }).click();
  const table = page.getByRole('region', { name: 'Таблица отчётов', exact: true });
  await expect(table.locator('[data-table-report-id]')).toHaveCount(2);
  expect(await table.locator('[data-table-report-id]').evaluateAll(elements => elements.map(element => element.getAttribute('data-table-report-id')))).toEqual(secondIds);
  await page.getByRole('button', { name: 'Открыть фильтры отчётов', exact: true }).click();
  const panel = page.getByRole('dialog', { name: 'Фильтры избранных отчётов', exact: true });
  await panel.locator('[data-panel-field="domain"]').click();
  await page.locator('[data-panel-value-list]').getByRole('checkbox', { name: 'Гостеприимство', exact: true }).check();
  await panel.getByRole('button', { name: 'Применить', exact: true }).click();
  await expect(table.locator('[data-table-report-id]')).toHaveCount(5);
  await expect(pager).toHaveCount(0);
});
