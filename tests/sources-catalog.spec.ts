test('source identity stays pinned with an operable header while other columns scroll behind it',async({page})=>{
  await page.setViewportSize({width:1024,height:600});
  await page.goto(entry);
  const scroll=page.getByLabel('Прокрутка таблицы источников',{exact:true});
  const table=page.getByRole('table',{name:'Источники',exact:true});
  const frame=page.locator('[data-source-table-scrolled]');
  const header=table.locator('th').first();
  const row=table.locator('tbody tr').first();
  const source=row.locator('td').first();
  const description=row.locator('td').nth(1);
  const initial={source:(await source.boundingBox())!,description:(await description.boundingBox())!,header:(await header.boundingBox())!};
  await scroll.evaluate(element=>element.scrollLeft=element.scrollWidth);
  await expect(frame).toHaveAttribute('data-source-table-scrolled','true');
  expect((await source.boundingBox())!.x).toBe(initial.source.x);
  expect((await source.boundingBox())!.width).toBe(initial.source.width);
  expect((await header.boundingBox())!.x).toBe(initial.header.x);
  expect((await description.boundingBox())!.x).toBeLessThan(initial.description.x);
  const hit=await source.evaluate(cell=>{
    const rect=cell.getBoundingClientRect();
    return cell.contains(document.elementFromPoint(rect.x+rect.width/2,rect.y+rect.height/2));
  });
  expect(hit).toBe(true);
  const left=await scroll.evaluate(element=>element.scrollLeft);
  await page.getByRole('button',{name:'Фильтр: Источник',exact:true}).click();
  await expect(page.getByRole('dialog',{name:'Фильтр: Источник',exact:true})).toBeVisible();
  expect(await scroll.evaluate(element=>element.scrollLeft)).toBe(left);
  await page.keyboard.press('Escape');
  await scroll.evaluate(element=>element.scrollTop=180);
  expect((await header.boundingBox())!.y).toBe(initial.header.y);
  expect((await header.boundingBox())!.x).toBe(initial.header.x);
  const divider=await frame.evaluate(element=>{
    const style=getComputedStyle(element,'::before');
    return{color:style.backgroundColor,height:style.height,top:style.top};
  });
  expect(divider).toEqual({color:'rgb(226, 228, 234)',height:'1px',top:'47px'});
  await scroll.evaluate(element=>element.scrollLeft=0);
  await expect(frame).toHaveAttribute('data-source-table-scrolled','false');
  expect((await source.boundingBox())!.x).toBe(initial.source.x);
});
