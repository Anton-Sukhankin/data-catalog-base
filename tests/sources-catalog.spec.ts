import { test, expect, type Locator } from '@playwright/test';
const entry = '/preview/navigation?section=sources';

test('source table headings match the report table insets', async ({ page }) => {
  const measure = (button: Locator) => button.evaluate(element => {
    const cell = element.closest('th, [role="columnheader"]')!.getBoundingClientRect();
    const control = element.parentElement!.getBoundingClientRect();
    const label = element.getBoundingClientRect();
    return { top:control.top-cell.top, left:control.left-cell.left, height:control.height,
      labelTop:label.top-cell.top, labelLeft:label.left-control.left };
  });

  await page.goto('/preview/navigation?section=reports');
  const first = await measure(page.getByRole('button', { name:'Фильтр «Отчёт»', exact:true }));
  const other = await measure(page.getByRole('button', { name:'Фильтр «Домен»', exact:true }));
  await page.goto(entry);
  expect(await measure(page.getByRole('button', { name:'Фильтр: Источник', exact:true }))).toEqual(first);
  expect(await measure(page.getByRole('button', { name:'Фильтр: Описание', exact:true }))).toEqual(other);
  await expect(page.getByRole('columnheader', { name:'Тип объекта', exact:true }).locator('span')).toHaveCSS('height', '32px');
  const head = (await page.getByRole('columnheader', { name:'Тип объекта', exact:true }).boundingBox())!;
  const row = (await page.locator('tbody tr').first().boundingBox())!;
  expect(row.y - (head.y + 48)).toBe(8);
});

