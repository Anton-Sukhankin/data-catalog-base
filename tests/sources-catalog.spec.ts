test('source table keeps reference text insets, centered headers and aligned columns while scrolling',async({page})=>{
  await page.setViewportSize({width:1024,height:600});
  await page.goto(entry);
  await page.evaluate(()=>document.fonts.ready);
  const table=page.getByRole('table',{name:'Источники',exact:true});
  const scroll=page.getByLabel('Прокрутка таблицы источников',{exact:true});
  const firstRow=table.locator('tbody tr').first();
  const firstTitle=firstRow.locator('td').first().locator('[data-overflow-text]').first();
  const headingText=table.locator('th').first().locator('button > span').first();
  const description=firstRow.locator('td').nth(1).locator('[data-overflow-text]');
  await expect(firstTitle).toHaveCSS('font-size','13px');
  await expect(description).toHaveCSS('color','rgb(148, 153, 163)');
  await expect(table.locator('td').nth(1)).toHaveCSS('vertical-align','middle');
  const cellBox=(await firstRow.locator('td').first().boundingBox())!;
  const iconBox=(await firstRow.locator('[data-catalog-entity-icon="source"]').boundingBox())!;
  expect(iconBox.x-cellBox.x).toBe(20);
  expect(iconBox.width).toBe(40);
  expect(iconBox.height).toBe(40);
  expect((await firstTitle.boundingBox())!.x-iconBox.x-iconBox.width).toBe(12);
  expect((await headingText.boundingBox())!.x-cellBox.x).toBe(20);
  const descriptionCell=(await firstRow.locator('td').nth(1).boundingBox())!;
  expect((await description.boundingBox())!.x-descriptionCell.x).toBe(12);
  const headerCenterOffsets=await table.locator('th').evaluateAll(cells=>cells.map(cell=>{
    const content=cell.querySelector('button > span') ?? cell.firstElementChild!;
    const rect=content.getBoundingClientRect();
    return rect.y+rect.height/2-cell.getBoundingClientRect().y;
  }));
  for(const center of headerCenterOffsets) expect(center).toBe(24);
  const headerY=(await table.locator('th').first().boundingBox())!.y;
  const scrollBox=(await scroll.boundingBox())!;
  const workspaceBox=(await page.getByRole('region',{name:'Каталог источников',exact:true}).boundingBox())!;
  expect(scrollBox.x-workspaceBox.x).toBe(16);
  expect(workspaceBox.x+workspaceBox.width-scrollBox.x-scrollBox.width).toBe(16);
  await scroll.hover();
  await page.mouse.wheel(560,180);
  await expect.poll(()=>scroll.evaluate(element=>element.scrollLeft)).toBeGreaterThan(0);
  await expect.poll(()=>scroll.evaluate(element=>element.scrollTop)).toBeGreaterThan(0);
  expect((await scroll.boundingBox())!.x).toBe(scrollBox.x);
  expect((await scroll.boundingBox())!.width).toBe(scrollBox.width);
  expect((await table.locator('th').first().boundingBox())!.y).toBe(headerY);
  const offsets=await table.evaluate(element=>{
    const headings=[...element.querySelectorAll('th')];
    return [...element.querySelectorAll('tbody tr:first-child td')].map((cell,index)=>cell.getBoundingClientRect().x-headings[index].getBoundingClientRect().x);
  });
  for(const offset of offsets) expect(Math.abs(offset)).toBeLessThan(1);
  await expect(scroll).toHaveCSS('scrollbar-width','none');
  expect(await page.evaluate(()=>document.documentElement.scrollWidth)).toBe(1024);
  await expect(page.locator('[data-source-pagination]')).toHaveCount(0);
  await expect(page.locator('vite-error-overlay')).toHaveCount(0);
});

